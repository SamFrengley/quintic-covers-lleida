    assert BettiNumbers(C) eq (n eq 6 select [1,9,16,9,1] else [1,14,35,35,14,1]);
    assert C`_Data`Resolution`Maps eq ResolutionMaps(C);
    assert C`_Data`Resolution`FirstSyzygies eq FirstSyzygies(C);
    Q,phi,cert := LocalDefiningPolynomials(C,1);
    assert #Q eq n-2;
    Q0 := C`_Data`Presentation`Polynomials;
    A := Parent(Q[1]);
    assert Matrix(A,#Q0,1,[phi(q) : q in Q0]) eq cert*Matrix(A,#Q,1,Q);
    Qagain,_,_ := LocalDefiningPolynomials(C,1);
    assert Qagain eq Q;
    for p in [2,3,5,7,11] do
        D,map := BaseChange(C,p);
        assert assigned D`StructureConstants and assigned D`Discriminant;
        assert D`StructureConstants eq [map(a) : a in C`StructureConstants];
        assert Discriminant(D) eq 1;
        FreshF := n eq 6 select StandardResolution6(GF(p)) else StandardResolution7(GF(p));
        Fresh := FiniteFlatCoverFromResolution(FreshF );
        assert StructureConstants(D) eq StructureConstants(Fresh);
        X := UnderlyingScheme(D);
        assert Dimension(X) eq 0 and Degree(X) eq n;
    end for;
    CK,phi := GenericFibre(C);
    R := BaseRing(CK);
    g := IdentityMatrix(R,n-1);
    g[1,1] := 2;
    g[1,2] := 3;
    g[2,3] := -1;
    H := [* IdentityMatrix(R,Ncols(A)) : A in ResolutionMaps(CK) *];
    H[#H][1,1] := 3;
    D := CK^<g,H>;
