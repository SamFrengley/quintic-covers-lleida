procedure RegressionCacheCheck(C)
    T := StructureConstants(C);
    assert C`StructureConstants eq T;
    L := MultiplicationMatrices(C);
    assert C`_Data`Algebra`Matrices eq L;
    v := TraceVector(C);
    assert C`_Data`Algebra`Traces eq v;
    H := TracePairing(C);
    assert C`_Data`Algebra`Pairing eq H;
    assert v eq [Trace(M) : M in L];
    assert H eq Matrix(BaseRing(C),Degree(C),Degree(C),[Trace(A*B) : A,B in L]);
    d := Discriminant(C);
    assert C`Discriminant eq d;
    Q := DefiningPolynomials(C);
    assert C`DefiningPolynomials eq Q;
    assert StructureConstants(C) eq T and MultiplicationMatrices(C) eq L and TracePairing(C) eq H;
end procedure;
